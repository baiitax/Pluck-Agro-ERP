import type { Metadata } from "next";
import Link from "next/link";
import { ClipboardCheck } from "lucide-react";

import { EmptyState } from "@/components/shared/empty-state";
import { FilterBar } from "@/components/shared/filter-bar";
import { PageHeader } from "@/components/shared/page-header";
import { Pagination } from "@/components/shared/pagination";
import { PermissionGuard } from "@/components/shared/permission-guard";
import { Badge } from "@/components/ui/badge";
import { buttonVariants } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Table, TBody, TD, TH, THead, TR, TableWrapper } from "@/components/ui/table";
import { formatDate } from "@/lib/formatting";
import { STOCK_COUNT_STATUSES, inventoryStatusTone, labelForInventoryStatus } from "@/lib/inventory/statuses";
import { cn } from "@/lib/utils";
import { requireActiveProfile } from "@/services/authorization";
import { listCounts } from "@/services/inventory/counts";

export const metadata: Metadata = { title: "Stock counts" };
export const dynamic = "force-dynamic";

/**
 * Stock counts.
 *
 * A count freezes the system quantity per lot at the moment it starts, then records what was found. The
 * variance is generated by the database from those two numbers, so it cannot be edited into agreement, and it
 * becomes a movement only after approval.
 */
export default async function CountsPage({
  searchParams,
}: {
  searchParams: Promise<{ status?: string; page?: string }>;
}) {
  const principal = await requireActiveProfile();
  if (!principal.permissions.has("inventory.count.view")) {
    return <PermissionGuard permission="inventory.count.view" />;
  }

  const params = await searchParams;
  const page = await listCounts({ status: params.status, page: params.page ? Number(params.page) : 1 });

  return (
    <div className="space-y-4">
      <PageHeader
        title="Stock counts"
        description="Counting compares what the ledger believes with what the shelf holds. The difference is a discovery, not a correction: it posts only after approval, and it always names the count that found it."
        breadcrumbs={[{ label: "Inventory", href: "/inventory" }, { label: "Counts" }]}
        actions={
          principal.permissions.has("inventory.count.execute") ? (
            <Link href="/inventory/counts/new" className={cn(buttonVariants({ size: "sm" }))}>
              Start a count
            </Link>
          ) : null
        }
      />

      <Card className="overflow-hidden">
        <FilterBar
          action="/inventory/counts"
          fields={[
            {
              type: "select",
              name: "status",
              label: "Status",
              options: [
                { value: "", label: "All statuses" },
                ...STOCK_COUNT_STATUSES.map((status) => ({ value: status, label: labelForInventoryStatus(status) })),
              ],
              defaultValue: params.status,
            },
          ]}
        />

        {page.rows.length === 0 ? (
          <EmptyState
            icon={ClipboardCheck}
            title="No counts"
            description="Nothing matches this filter. Starting a count freezes the system quantity for every open lot with a balance in the chosen warehouse."
          />
        ) : (
          <>
            <TableWrapper>
              <Table>
                <THead>
                  <TR>
                    <TH>Reference</TH>
                    <TH>Warehouse</TH>
                    <TH>Count date</TH>
                    <TH>Status</TH>
                    <TH className="text-right">Lines counted</TH>
                    <TH className="text-right">Gain</TH>
                    <TH className="text-right">Loss</TH>
                    <TH>Posted</TH>
                  </TR>
                </THead>
                <TBody>
                  {page.rows.map((row) => (
                    <TR key={row.id}>
                      <TD>
                        <Link
                          href={`/inventory/counts/${row.id}`}
                          className="font-mono text-xs font-medium text-brand-700 hover:underline"
                        >
                          {row.reference}
                        </Link>
                      </TD>
                      <TD>{row.warehouseName ?? "—"}</TD>
                      <TD>{formatDate(row.count_date)}</TD>
                      <TD>
                        <Badge tone={inventoryStatusTone(row.status)} dot>
                          {labelForInventoryStatus(row.status)}
                        </Badge>
                      </TD>
                      <TD className="text-right tabular-nums">
                        {row.countedLines}/{row.lineCount}
                      </TD>
                      <TD className="text-right tabular-nums">{Number(row.total_gain_quantity)}</TD>
                      <TD className="text-right tabular-nums">{Number(row.total_loss_quantity)}</TD>
                      <TD className="text-xs">{row.posted_at ? formatDate(row.posted_at) : "—"}</TD>
                    </TR>
                  ))}
                </TBody>
              </Table>
            </TableWrapper>
            <Pagination
              page={page.page}
              pageSize={page.pageSize}
              total={page.total}
              baseHref="/inventory/counts"
              params={{ status: params.status }}
            />
          </>
        )}
      </Card>
    </div>
  );
}
