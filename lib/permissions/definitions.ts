type CatalogEntry = (typeof CATALOG)[number];

export type PermissionCode =
  `${CatalogEntry["module"]}.${CatalogEntry["resource"]}.${CatalogEntry["action"]}`;

export type PermissionDefinition = {
  module: string;
  resource: string;
  action: PermissionAction;
  description: string;
};

export const PERMISSION_CATALOG: Record<PermissionCode, PermissionDefinition> = Object.fromEntries(
  CATALOG.map((entry) => [`${entry.module}.${entry.resource}.${entry.action}`, entry]),
) as Record<PermissionCode, PermissionDefinition>;

export const ALL_PERMISSION_CODES = Object.keys(PERMISSION_CATALOG) as PermissionCode[];

export function isPermissionCode(value: string): value is PermissionCode {
  return Object.prototype.hasOwnProperty.call(PERMISSION_CATALOG, value);
}

export function permissionLabel(code: string): string {
  const definition: PermissionDefinition | undefined = PERMISSION_CATALOG[code as PermissionCode];
  return definition ? definition.description : code;
}

export function permissionModule(code: string): string {
  const definition: PermissionDefinition | undefined = PERMISSION_CATALOG[code as PermissionCode];
  return definition ? definition.module : (code.split(".")[0] ?? "unknown");
}

export function permissionResource(code: string): string {
  const definition: PermissionDefinition | undefined = PERMISSION_CATALOG[code as PermissionCode];
  return definition ? definition.resource : "unknown";
}

export function permissionAction(code: string): string {
  const definition: PermissionDefinition | undefined = PERMISSION_CATALOG[code as PermissionCode];
  return definition ? definition.action : "unknown";
}

/** Permission codes grouped by module/resource, used by the matrix and role editors. */
export function groupedPermissions(): { module: string; resource: string; codes: PermissionCode[] }[] {
  const groups = new Map<string, PermissionCode[]>();
  for (const code of ALL_PERMISSION_CODES) {
    const definition = PERMISSION_CATALOG[code] as PermissionDefinition;
    const key = `${definition.module}.${definition.resource}`;
    groups.set(key, [...(groups.get(key) ?? []), code]);
  }
  return [...groups.entries()].map(([key, codes]) => {
    const [module = "unknown", resource = "unknown"] = key.split(".");
    return { module, resource, codes };
  });
}

