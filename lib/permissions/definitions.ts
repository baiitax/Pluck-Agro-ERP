/**
 * Canonical permission catalogue (Phase 1 scheme: `module.resource.action`).
 *
 * This module must stay dependency-free: `scripts/generate-seed-sql.mjs` transpiles and
 * imports it to generate the SQL seed migrations, so the database and the application can
 * never drift apart. `tests/unit/permissions.test.ts` asserts that parity.
 *
 * Codes are controlled system data. Administrators may change role → permission grants, but
 * they cannot invent new permission codes at runtime.
 */

