import "server-only";

import { revalidatePath } from "next/cache";

import { AppError } from "@/lib/errors";
import { validateAuthorityAmounts, validateAuthorityWindow } from "@/lib/governance/authority";
import { createSupabaseServerClient } from "@/lib/supabase/server";
import { authorityCreateSchema, authorityUpdateSchema } from "@/lib/validation/schemas";
import { requirePermission } from "@/services/authorization";
import { recordAuditEvent } from "@/services/audit/record-audit-event";
import type { RequestMeta } from "@/services/employees/manage-employee";
import type { ApprovalAuthority } from "@/types/database.types";

export type AuthorityWithPrincipal = ApprovalAuthority & {
  employee: { id: string; employee_number: string; first_name: string; last_name: string } | null;
  role: { id: string; code: string; name: string } | null;
  department: { id: string; name: string } | null;
};

const SELECT =
  "*, employee:employees!approval_authorities_employee_id_fkey(id, employee_number, first_name, last_name), role:roles!approval_authorities_role_id_fkey(id, code, name), department:departments!approval_authorities_department_id_fkey(id, name)";

export async function getAuthorities(): Promise<AuthorityWithPrincipal[]> {
  const supabase = await createSupabaseServerClient();
  const { data, error } = await supabase
    .from("approval_authorities")
    .select(SELECT)
    .order("created_at", { ascending: false })
    .returns<AuthorityWithPrincipal[]>();
  if (error) throw new Error(error.message);
  return data ?? [];
}

export async function getAuthoritiesForEmployee(employeeId: string): Promise<ApprovalAuthority[]> {
  const supabase = await createSupabaseServerClient();
  const { data, error } = await supabase
    .from("approval_authorities")
    .select("*")
    .eq("employee_id", employeeId)
    .returns<ApprovalAuthority[]>();
  if (error) throw new Error(error.message);
  return data ?? [];
}

/**
 * Records an approval authority limit.
 *
 * This is configuration only: Phase 1 has no approval workflow, so nothing here approves a
 * transaction. No Pluck Agro limit is ever generated by the system — every row exists because an
 * administrator entered it with a justification and a validity window.
 */
export async function createAuthority(input: unknown, meta: RequestMeta = {}): Promise<ApprovalAuthority> {
  const actor = await requirePermission("governance.approvals.configure");
  const payload = authorityCreateSchema.parse(input);

  const issues = [
    ...validateAuthorityAmounts(payload.minimumAmount, payload.maximumAmount),
    ...validateAuthorityWindow({ effectiveFrom: payload.effectiveFrom, effectiveUntil: payload.effectiveUntil }),
  ];
  if (issues.length > 0) {
    throw new AppError("VALIDATION_ERROR", issues.map((issue) => issue.message).join(" "), {
      details: Object.fromEntries(issues.map((issue) => [issue.field, [issue.message]])),
    });
  }

  const supabase = await createSupabaseServerClient();
  const { data, error } = await supabase
    .from("approval_authorities")
    .insert({
      employee_id: payload.principalType === "employee" ? payload.employeeId || null : null,
      role_id: payload.principalType === "role" ? payload.roleId || null : null,
      department_id: payload.departmentId || null,
      module: payload.module.trim().toLowerCase(),
      transaction_type: payload.transactionType.trim(),
      authority_level: payload.authorityLevel,
      currency_code: payload.currencyCode,
      minimum_amount: payload.minimumAmount,
      maximum_amount: payload.maximumAmount,
      scope_type: payload.scopeType,
      effective_from: payload.effectiveFrom,
      effective_until: payload.effectiveUntil || null,
      justification: payload.justification,
      is_active: true,
      created_by: actor.user.id,
      updated_by: actor.user.id,
    })
    .select("*")
    .single<ApprovalAuthority>();

  if (error) {
    if (error.code === "23514") {
      throw new AppError("VALIDATION_ERROR", "The database rejected this authority: check the principal, amounts and dates.");
    }
    throw new Error(error.message);
  }

  await recordAuditEvent({
    actorUserId: actor.user.id,
    actorEmployeeId: actor.employee?.id ?? null,
    action: "authority.created",
    eventCategory: "governance",
    severity: "warning",
    module: "governance",
    entityType: "approval_authority",
    entityId: data.id,
    description: `Configured ${data.module}/${data.transaction_type} approval authority up to ${data.currency_code} ${data.maximum_amount}.`,
    newValues: {
      employee_id: data.employee_id,
      role_id: data.role_id,
      module: data.module,
      transaction_type: data.transaction_type,
      currency_code: data.currency_code,
      minimum_amount: data.minimum_amount,
      maximum_amount: data.maximum_amount,
      effective_from: data.effective_from,
      effective_until: data.effective_until,
    },
    metadata: { justification: payload.justification },
    requestId: meta.requestId ?? null,
    ipAddress: meta.ipAddress ?? null,
    userAgent: meta.userAgent ?? null,
  });

  revalidatePath("/governance/authorities");
  return data;
}

export async function updateAuthority(input: unknown, meta: RequestMeta = {}): Promise<ApprovalAuthority> {
  const actor = await requirePermission("governance.approvals.configure");
  const payload = authorityUpdateSchema.parse(input);

  const issues = [
    ...validateAuthorityAmounts(payload.minimumAmount, payload.maximumAmount),
    ...validateAuthorityWindow({ effectiveFrom: new Date().toISOString().slice(0, 10), effectiveUntil: payload.effectiveUntil }),
  ];
  if (issues.length > 0) {
    throw new AppError("VALIDATION_ERROR", issues.map((issue) => issue.message).join(" "));
  }

  const supabase = await createSupabaseServerClient();
  const { data: existing, error: readError } = await supabase
    .from("approval_authorities")
    .select("*")
    .eq("id", payload.id)
    .maybeSingle<ApprovalAuthority>();
  if (readError) throw new Error(readError.message);
  if (!existing) throw new AppError("NOT_FOUND", "That authority record does not exist.");

  const { data, error } = await supabase
    .from("approval_authorities")
    .update({
      minimum_amount: payload.minimumAmount,
      maximum_amount: payload.maximumAmount,
      authority_level: payload.authorityLevel,
      effective_until: payload.effectiveUntil || null,
      justification: payload.justification,
      is_active: payload.isActive,
      updated_by: actor.user.id,
    })
    .eq("id", payload.id)
    .select("*")
    .single<ApprovalAuthority>();
  if (error) throw new Error(error.message);

  await recordAuditEvent({
    actorUserId: actor.user.id,
    actorEmployeeId: actor.employee?.id ?? null,
    action: "authority.updated",
    eventCategory: "governance",
    severity: "warning",
    module: "governance",
    entityType: "approval_authority",
    entityId: data.id,
    description: `Updated approval authority for ${data.module}/${data.transaction_type}.`,
    oldValues: {
      minimum_amount: existing.minimum_amount,
      maximum_amount: existing.maximum_amount,
      authority_level: existing.authority_level,
      is_active: existing.is_active,
      effective_until: existing.effective_until,
    },
    newValues: {
      minimum_amount: data.minimum_amount,
      maximum_amount: data.maximum_amount,
      authority_level: data.authority_level,
      is_active: data.is_active,
      effective_until: data.effective_until,
    },
    metadata: { justification: payload.justification },
    requestId: meta.requestId ?? null,
    ipAddress: meta.ipAddress ?? null,
    userAgent: meta.userAgent ?? null,
  });

  revalidatePath("/governance/authorities");
  return data;
}
